// Builds, checks and publishes the art history with plain git plumbing.
import { spawnSync } from 'node:child_process';
import { epochSeconds } from './art.mjs';

export function git(repo, args, env, input) {
  const result = spawnSync('git', args, {
    cwd: repo,
    encoding: 'utf8',
    input,
    env: env ? { ...process.env, ...env } : process.env,
    maxBuffer: 1 << 28,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${result.stderr.trim()}`);
  return result.stdout.trim();
}

function commit(repo, config, { tree, parent, date, second, message }) {
  const stamp = `${epochSeconds(date, config.time, config.timezone) + second} ${config.timezone}`;
  const args = ['commit-tree', tree, '--no-gpg-sign', '-m', message];
  if (parent) args.push('-p', parent);
  return git(repo, args, {
    GIT_AUTHOR_NAME: config.author.name,
    GIT_AUTHOR_EMAIL: config.author.email,
    GIT_AUTHOR_DATE: stamp,
    GIT_COMMITTER_NAME: config.author.name,
    GIT_COMMITTER_EMAIL: config.author.email,
    GIT_COMMITTER_DATE: stamp,
  });
}

// The art repository's only file: a README saying where it comes from.
export function artReadme(config) {
  return `# ${config.repo.split('/')[1]}\n\nContribution graph art, generated by https://github.com/jameschapman2c/hacker-art.\nThis repository is deleted and recreated at every refresh.\n`;
}

function artTree(repo, config) {
  const blob = git(repo, ['hash-object', '-w', '--stdin'], undefined, artReadme(config));
  return git(repo, ['mktree'], undefined, `100644 blob ${blob}\tREADME.md\n`);
}

// A root commit holding the README, dated the day before the graph starts (off the graph), then
// one empty commit per planned contribution. Returns the tip; the same config and plan give the same hash.
export function buildHistory(repo, config, plan) {
  const tree = artTree(repo, config);
  let parent = commit(repo, config, { tree, date: plan.baseDate, second: 0, message: config.baseMessage });
  for (const day of plan.days) {
    for (let i = 0; i < day.commits; i += 1) {
      parent = commit(repo, config, { tree, parent, date: day.date, second: i, message: config.message });
    }
  }
  return parent;
}

// Commits per calendar day (in each commit's own timezone) by the author email on `ref`.
export function commitsPerDay(repo, ref, email) {
  const counts = new Map();
  const log = git(repo, ['log', ref, '--format=%ae %ad', '--date=format:%Y-%m-%d']);
  for (const line of log.split('\n').filter(Boolean)) {
    const [author, date] = line.split(' ');
    if (author.toLowerCase() === email.toLowerCase()) counts.set(date, (counts.get(date) ?? 0) + 1);
  }
  return counts;
}

// Days inside the graph window whose commit count differs from the plan.
export function compareWithPlan(plan, counts) {
  const expected = new Map(plan.days.map((day) => [day.date, day.commits]));
  const dates = new Set([...expected.keys(), ...counts.keys()]);
  return [...dates]
    .filter((date) => date >= plan.window.start && date <= plan.today)
    .sort()
    .map((date) => ({ date, expected: expected.get(date) ?? 0, actual: counts.get(date) ?? 0 }))
    .filter((day) => day.expected !== day.actual);
}
